"""Document processing and OCR ingestion endpoints."""

import os
import shutil
import uuid
from pathlib import Path
from fastapi import APIRouter, Depends, HTTPException, UploadFile, File
from sqlalchemy.orm import Session

from app.database import get_db
from app.auth import owned_case
from app.config import settings
from app.models import Case, EvidenceDocument, TimelineEvent, DialogueTurn
from app.schemas import DocumentUploadResponse
from app.services.document_processor import process_document, categorize_document
from app.services.timeline_evidence_engine import EvidenceEngine, EVIDENCE_REQUIREMENTS

ALLOWED_EXTS = {".pdf", ".png", ".jpg", ".jpeg", ".webp", ".txt", ".mp4", ".mov"}
MAX_UPLOAD_BYTES = 10 * 1024 * 1024

router = APIRouter(prefix="/api/documents", tags=["Documents"])


@router.post("/upload/{case_id}", response_model=DocumentUploadResponse)
async def upload_document(
    case_id: str,
    file: UploadFile = File(...),
    _owner: Case = Depends(owned_case),
    db: Session = Depends(get_db),
):
    """Upload an invoice, receipt, or chat screenshot, run OCR, and extract fields."""
    case = db.query(Case).filter(Case.id == case_id).first()
    if not case:
        raise HTTPException(status_code=404, detail="Case not found")

    # Ensure uploads directory exists
    os.makedirs(settings.UPLOAD_DIR, exist_ok=True)

    # Generate unique filename on disk
    file_ext = Path(file.filename or "").suffix.lower()
    if file_ext not in ALLOWED_EXTS:
        raise HTTPException(status_code=415, detail=f"Unsupported file type. Allowed: {', '.join(sorted(ALLOWED_EXTS))}")
    data = await file.read(MAX_UPLOAD_BYTES + 1)
    if len(data) > MAX_UPLOAD_BYTES:
        raise HTTPException(status_code=413, detail="File too large (max 10 MB)")
    if not data:
        raise HTTPException(status_code=400, detail="Empty file")
    doc_id = str(uuid.uuid4())
    save_filename = f"{doc_id}{file_ext}"
    dest_path = os.path.join(settings.UPLOAD_DIR, save_filename)

    with open(dest_path, "wb") as buffer:
        buffer.write(data)

    # Process document OCR & extraction
    clean_ext = file_ext.replace(".", "")
    doc_result = process_document(dest_path, file_type=clean_ext)
    ocr_content = doc_result.get("ocr_text", "") or ""
    ext_fields = doc_result.get("extracted_fields", {}) or {}

    # Auto-categorize document
    categorized_as = categorize_document(ocr_content, file.filename, clean_ext)
    ext_fields["document_type"] = categorized_as

    # Create EvidenceDocument record in DB
    evidence_doc = EvidenceDocument(
        id=doc_id,
        case_id=case_id,
        filename=file.filename,
        file_path=dest_path,
        file_type=clean_ext,
        ocr_text=ocr_content,
        extracted_fields=ext_fields,
        processing_status=doc_result.get("status", "processed"),
    )
    db.add(evidence_doc)

    # Mark evidence uploaded on case
    case.evidence_uploaded = True

    # If OCR extracted an invoice date or vendor, add to timeline
    if ext_fields.get("invoice_date"):
        db.add(TimelineEvent(
            case_id=case_id,
            event_date=ext_fields["invoice_date"],
            event_type="ocr_invoice_issued",
            description=f"Tax Invoice generated by {ext_fields.get('vendor', 'Merchant')}. Amount: ₹{ext_fields.get('total_amount', 'N/A')}",
            source="ocr_extracted",
        ))

    db.commit()
    db.refresh(evidence_doc)

    # Recalculate gap analysis & readiness score in real-time
    ev_engine = EvidenceEngine()
    gap_res = ev_engine.compute_gap_analysis(case_id, db)

    # Build targeted bot acknowledgment message for in-chat feed
    cat = case.issue_category or "Other"
    cat_reqs = EVIDENCE_REQUIREMENTS.get(cat, EVIDENCE_REQUIREMENTS.get("Other", {}))
    req_needed = cat_reqs.get("required", [])
    rec_needed = cat_reqs.get("recommended", [])
    submitted_set = set(gap_res.get("submitted", []))

    still_missing_req = [r for r in req_needed if r not in submitted_set]
    still_missing_rec = [r for r in rec_needed if r not in submitted_set]

    if still_missing_req:
        needed_str = "\n".join(f"• **{item}** *(Required)*" for item in still_missing_req[:3])
        next_prompt = f"To strengthen your case, we still need:\n{needed_str}\n\nPlease attach the next file, or click **[Skip / Proceed to Stage 5]** if you do not have it."
    elif still_missing_rec:
        needed_str = "\n".join(f"• **{item}** *(Optional)*" for item in still_missing_rec[:2])
        next_prompt = f"All required documents are verified! You can optionally upload:\n{needed_str}\n\nOr click **[Proceed to Stage 5: Timeline Reconstruction]**."
    else:
        next_prompt = "🎉 All statutory evidence requirements are 100% fulfilled! Click **[Proceed to Stage 5: Timeline Reconstruction]**."

    bot_ack = (
        f"✅ I have successfully received and categorized your **{categorized_as}** (`{file.filename}`).\n\n"
        f"**Case Readiness Score:** {gap_res.get('readiness_score', 0)}%\n\n"
        f"{next_prompt}"
    )

    # Insert user turn and assistant acknowledgment into chat dialogue
    current_turns = db.query(DialogueTurn).filter(DialogueTurn.case_id == case_id).all()
    max_turn = max([t.turn_number for t in current_turns], default=0)

    user_upload_turn = DialogueTurn(
        case_id=case_id,
        turn_number=max_turn + 1,
        role="user",
        message=f"📎 [Uploaded Document: {file.filename} — Categorized as {categorized_as}]",
    )
    assistant_ack_turn = DialogueTurn(
        case_id=case_id,
        turn_number=max_turn + 2,
        role="assistant",
        message=bot_ack,
    )
    db.add(user_upload_turn)
    db.add(assistant_ack_turn)
    db.commit()

    return DocumentUploadResponse(
        document_id=evidence_doc.id,
        filename=evidence_doc.filename,
        file_type=evidence_doc.file_type,
        processing_status=evidence_doc.processing_status,
        ocr_text=evidence_doc.ocr_text,
        extracted_fields=evidence_doc.extracted_fields,
        categorized_as=categorized_as,
        assistant_message=bot_ack,
        readiness_score=gap_res.get("readiness_score", 0.0),
        checklist=gap_res.get("checklist", {}),
    )

